CREATE FUNCTION public.notificaciones_email_marcar_enviada(
    p_id BIGINT,
    p_token UUID,
    p_proveedor_mensaje_id TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
    PERFORM petstore_private.requerir_usuario_activo();
    UPDATE public.notificaciones_email
    SET estado = 'sent',
        proveedor_mensaje_id = NULLIF(BTRIM(p_proveedor_mensaje_id), ''),
        ultimo_error = NULL,
        enviado_en = CURRENT_TIMESTAMP,
        procesando_token = NULL,
        procesando_en = NULL,
        actualizado_en = CURRENT_TIMESTAMP
    WHERE id = p_id AND estado = 'pending' AND procesando_token = p_token;
    RETURN FOUND;
END;
$$;

CREATE FUNCTION public.notificaciones_email_marcar_fallida(
    p_id BIGINT,
    p_token UUID,
    p_error TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
    PERFORM petstore_private.requerir_usuario_activo();
    UPDATE public.notificaciones_email
    SET estado = 'failed',
        ultimo_error = LEFT(COALESCE(NULLIF(BTRIM(p_error), ''), 'email_send_failed'), 100),
        procesando_token = NULL,
        procesando_en = NULL,
        actualizado_en = CURRENT_TIMESTAMP
    WHERE id = p_id AND estado = 'pending' AND procesando_token = p_token;
    RETURN FOUND;
END;
$$;

CREATE FUNCTION public.notificaciones_email_listar(
    p_limite BIGINT DEFAULT 25,
    p_offset BIGINT DEFAULT 0,
    p_desde DATE DEFAULT NULL,
    p_hasta DATE DEFAULT NULL,
    p_cliente_id BIGINT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE v_resultado JSONB;
BEGIN
    PERFORM petstore_private.requerir_usuario_activo();
    PERFORM petstore_private.validar_paginacion(p_limite, p_offset);
    IF p_desde IS NOT NULL AND p_hasta IS NOT NULL AND p_hasta < p_desde THEN
        RAISE EXCEPTION USING ERRCODE = 'PV001', MESSAGE = 'RANGO_DE_FECHAS_INVALIDO';
    END IF;

    WITH base AS (
        SELECT n.*, cl.nombre AS cliente_nombre, m.nombre AS mascota_nombre,
               s.nombre AS sucursal_nombre, sv.nombre AS servicio_nombre
        FROM public.notificaciones_email n
        INNER JOIN public.citas c ON c.id = n.cita_id
        INNER JOIN public.mascotas m ON m.id = c.mascota_id
        INNER JOIN public.clientes cl ON cl.id = m.cliente_id
        INNER JOIN public.sucursales s ON s.id = c.sucursal_id
        INNER JOIN public.registros_servicio rs ON rs.id = n.registro_servicio_id
        INNER JOIN public.servicios sv ON sv.id = rs.servicio_id
        WHERE (p_desde IS NULL OR n.creado_en >= (p_desde::TIMESTAMP AT TIME ZONE 'America/Guatemala'))
          AND (p_hasta IS NULL OR n.creado_en < ((p_hasta + 1)::TIMESTAMP AT TIME ZONE 'America/Guatemala'))
          AND (p_cliente_id IS NULL OR n.cliente_id = p_cliente_id)
          AND petstore_private.tiene_acceso_sucursal(c.sucursal_id)
    ), pagina AS (
        SELECT * FROM base ORDER BY creado_en DESC, id DESC LIMIT p_limite OFFSET p_offset
    )
    SELECT JSONB_BUILD_OBJECT(
        'datos', COALESCE((SELECT JSONB_AGG(TO_JSONB(p) ORDER BY p.creado_en DESC, p.id DESC) FROM pagina p), '[]'::JSONB),
        'total', (SELECT COUNT(*) FROM base),
        'limite', p_limite,
        'offset', p_offset
    ) INTO v_resultado;
    RETURN v_resultado;
END;
$$;

