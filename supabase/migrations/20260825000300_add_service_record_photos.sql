CREATE TABLE public.registros_servicio_fotos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_servicio_id BIGINT NOT NULL
        REFERENCES public.registros_servicio(id) ON DELETE RESTRICT,
    momento TEXT NOT NULL CHECK (momento IN ('ingreso', 'egreso')),
    ruta_storage TEXT NOT NULL
        CHECK (BTRIM(ruta_storage) LIKE 'services/%'),
    subida_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (registro_servicio_id, ruta_storage)
);

CREATE INDEX ix_registros_servicio_fotos_registro_momento
    ON public.registros_servicio_fotos (registro_servicio_id, momento, id);

INSERT INTO public.registros_servicio_fotos (
    registro_servicio_id,
    momento,
    ruta_storage,
    subida_en
)
SELECT id, 'ingreso', foto_antes_url, COALESCE(foto_antes_subida_en, creado_en)
FROM public.registros_servicio
WHERE foto_antes_url IS NOT NULL
UNION ALL
SELECT id, 'egreso', foto_despues_url, COALESCE(foto_despues_subida_en, creado_en)
FROM public.registros_servicio
WHERE foto_despues_url IS NOT NULL
ON CONFLICT (registro_servicio_id, ruta_storage) DO NOTHING;

ALTER TABLE public.registros_servicio_fotos ENABLE ROW LEVEL SECURITY;

