        FROM pg_proc p
        INNER JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'public'
          AND p.proname IN (
              'registros_servicio_insertar',
              'registros_servicio_iniciar',
              'registros_servicio_actualizar',
              'registros_servicio_completar'
          )
    LOOP
        EXECUTE FORMAT('REVOKE ALL ON FUNCTION %I.%I(%s) FROM PUBLIC, anon', v_funcion.esquema, v_funcion.nombre, v_funcion.argumentos);
        EXECUTE FORMAT('GRANT EXECUTE ON FUNCTION %I.%I(%s) TO authenticated, service_role', v_funcion.esquema, v_funcion.nombre, v_funcion.argumentos);
    END LOOP;
END;
