CREATE TABLE public.paquetes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL CHECK (BTRIM(nombre) <> ''),
    precio NUMERIC(10, 2) NOT NULL CHECK (precio > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_por_usuario_id UUID NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_paquetes_nombre_lower ON public.paquetes (LOWER(nombre));

CREATE TABLE public.paquetes_servicios (
    paquete_id BIGINT NOT NULL REFERENCES public.paquetes(id) ON DELETE CASCADE,
    servicio_id BIGINT NOT NULL REFERENCES public.servicios(id) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (paquete_id, servicio_id)
);

CREATE TABLE public.paquetes_asignaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paquete_id BIGINT NOT NULL REFERENCES public.paquetes(id) ON DELETE RESTRICT,
    cliente_id BIGINT NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
    precio_pagado NUMERIC(10, 2) NOT NULL CHECK (precio_pagado > 0),
    asignado_por_usuario_id UUID NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    asignado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_paquetes_asignaciones_cliente ON public.paquetes_asignaciones (cliente_id, asignado_en DESC);
CREATE INDEX ix_paquetes_asignaciones_paquete ON public.paquetes_asignaciones (paquete_id, asignado_en DESC);

ALTER TABLE public.cupones
    ADD COLUMN paquete_asignacion_id BIGINT NULL
        REFERENCES public.paquetes_asignaciones(id) ON DELETE RESTRICT;

ALTER TABLE public.cupones
    DROP CONSTRAINT IF EXISTS cupones_origen_valido,
    ADD CONSTRAINT cupones_origen_valido CHECK (origen IN ('manual', 'automatico', 'paquete')),
    ADD CONSTRAINT cupones_paquete_validos CHECK (
        origen <> 'paquete'
        OR (
            cliente_id IS NOT NULL
            AND servicio_id IS NOT NULL
            AND tipo_descuento = 'porcentaje'
            AND valor = 100
            AND uso_unico = TRUE
            AND paquete_asignacion_id IS NOT NULL
        )
    );

CREATE INDEX ix_cupones_paquete_asignacion ON public.cupones (paquete_asignacion_id, servicio_id, activo);

ALTER TABLE public.paquetes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.paquetes_servicios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.paquetes_asignaciones ENABLE ROW LEVEL SECURITY;

