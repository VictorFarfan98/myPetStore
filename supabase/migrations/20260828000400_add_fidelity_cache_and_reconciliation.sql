CREATE TRIGGER trg_crear_fidelidad_cliente
AFTER INSERT ON public.clientes
FOR EACH ROW EXECUTE FUNCTION petstore_private.crear_fidelidad_cliente();

CREATE OR REPLACE FUNCTION public.clientes_progreso_fidelidad_listar()
RETURNS JSONB
LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $$
DECLARE v_resultado JSONB;
BEGIN
    PERFORM petstore_private.requerir_usuario_activo();

    SELECT COALESCE(JSONB_AGG(JSONB_BUILD_OBJECT(
        'cliente_id', c.id,
        'completados', MOD(COALESCE(fc.creditos_acumulados, 0), config.servicios_requeridos_cupon),
        'requeridos', config.servicios_requeridos_cupon
    ) ORDER BY c.id), '[]'::JSONB)
    INTO v_resultado
    FROM public.clientes c
    CROSS JOIN public.configuracion_sistema config
    LEFT JOIN public.fidelidad_clientes fc ON fc.cliente_id = c.id
    WHERE c.activo = TRUE
      AND config.id = 1;

    RETURN v_resultado;
END;
$$;

CREATE FUNCTION public.clientes_fidelidad_actualizar(
    p_cliente_id BIGINT,
    p_completados INTEGER,
    p_motivo TEXT
)
RETURNS public.fidelidad_clientes
LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $$
DECLARE
    v_actor UUID;
    v_requeridos INTEGER;
    v_anterior BIGINT;
    v_nuevo BIGINT;
    v_fila public.fidelidad_clientes;
BEGIN
    v_actor := petstore_private.requerir_admin_propietario();
    PERFORM petstore_private.establecer_actor();

    IF p_motivo IS NULL OR BTRIM(p_motivo) = '' THEN
        RAISE EXCEPTION USING ERRCODE = 'PV001', MESSAGE = 'MOTIVO_REQUERIDO';
    END IF;

    SELECT servicios_requeridos_cupon
    INTO v_requeridos
    FROM public.configuracion_sistema
    WHERE id = 1;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = 'PN001', MESSAGE = 'CONFIGURACION_SISTEMA_NO_ENCONTRADA';
    END IF;
    IF p_completados IS NULL OR p_completados < 0 OR p_completados >= v_requeridos THEN
        RAISE EXCEPTION USING ERRCODE = 'PV001', MESSAGE = 'PROGRESO_FIDELIDAD_INVALIDO';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.clientes WHERE id = p_cliente_id AND activo = TRUE) THEN
        RAISE EXCEPTION USING ERRCODE = 'PN001', MESSAGE = 'CLIENTE_NO_ENCONTRADO';
    END IF;

    SELECT COALESCE(creditos_acumulados, 0)
    INTO v_anterior
    FROM public.fidelidad_clientes
    WHERE cliente_id = p_cliente_id
    FOR UPDATE;

    v_anterior := COALESCE(v_anterior, 0);
    v_nuevo := v_anterior - MOD(v_anterior, v_requeridos) + p_completados;

    INSERT INTO public.fidelidad_clientes (cliente_id, creditos_acumulados)
    VALUES (p_cliente_id, v_nuevo)
    ON CONFLICT (cliente_id) DO UPDATE
    SET creditos_acumulados = EXCLUDED.creditos_acumulados
    RETURNING * INTO v_fila;

    INSERT INTO public.fidelidad_ajustes (
        cliente_id,
        creditos_anteriores,
        creditos_nuevos,
        completados_anteriores,
        completados_nuevos,
        motivo,
        usuario_id
    )
    VALUES (
        p_cliente_id,
        v_anterior,
        v_nuevo,
        MOD(v_anterior, v_requeridos),
        p_completados,
        BTRIM(p_motivo),
        v_actor
    );

    PERFORM petstore_private.auditar_cambio(
        'fidelidad_clientes', p_cliente_id::TEXT, 'ajustar',
        JSONB_BUILD_OBJECT('completados', MOD(v_anterior, v_requeridos)),
        JSONB_BUILD_OBJECT('completados', p_completados),
        NULL, BTRIM(p_motivo)
    );

    RETURN v_fila;
END;
$$;

CREATE FUNCTION public.clientes_fidelidad_reconciliar()
RETURNS JSONB
LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $$
DECLARE v_resultado JSONB;
BEGIN
    PERFORM petstore_private.requerir_admin_propietario();

    WITH config AS (
        SELECT servicios_requeridos_cupon, fidelidad_inicia_en
        FROM public.configuracion_sistema
        WHERE id = 1
    ), esperados AS (
        SELECT c.id AS cliente_id,
               c.nombre AS cliente_nombre,
               COUNT(rs.id)::BIGINT AS servicios_completados
        FROM public.clientes c
        CROSS JOIN config
        LEFT JOIN public.mascotas m ON m.cliente_id = c.id
        LEFT JOIN public.citas ci ON ci.mascota_id = m.id
        LEFT JOIN public.registros_servicio rs
           ON rs.cita_id = ci.id
           AND rs.estado = 'completado'
           AND rs.activo = TRUE
           AND rs.fin_real >= config.fidelidad_inicia_en
        LEFT JOIN public.cupones cp ON cp.id = rs.cupon_id
        WHERE c.activo = TRUE
          AND (rs.cupon_id IS NULL OR cp.uso_unico = FALSE)
        GROUP BY c.id, c.nombre, config.servicios_requeridos_cupon
    ), diferencias AS (
        SELECT e.cliente_id,
               e.cliente_nombre,
               MOD(COALESCE(fc.creditos_acumulados, 0), config.servicios_requeridos_cupon) AS actual,
               MOD(e.servicios_completados, config.servicios_requeridos_cupon) AS esperado,
               e.servicios_completados
        FROM esperados e
        CROSS JOIN config
        LEFT JOIN public.fidelidad_clientes fc ON fc.cliente_id = e.cliente_id
    )
    SELECT COALESCE(JSONB_AGG(JSONB_BUILD_OBJECT(
        'cliente_id', cliente_id,
        'cliente_nombre', cliente_nombre,
        'actual', actual,
        'esperado', esperado,
        'servicios_completados', servicios_completados,
        'requeridos', config.servicios_requeridos_cupon
    ) ORDER BY cliente_nombre, cliente_id) FILTER (WHERE actual IS DISTINCT FROM esperado), '[]'::JSONB)
    INTO v_resultado
    FROM diferencias
    CROSS JOIN config;

    RETURN v_resultado;
END;
$$;

