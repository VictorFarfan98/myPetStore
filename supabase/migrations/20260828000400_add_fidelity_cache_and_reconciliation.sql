CREATE TABLE public.fidelidad_clientes (
    cliente_id BIGINT PRIMARY KEY
        REFERENCES public.clientes(id) ON DELETE RESTRICT,
    creditos_acumulados BIGINT NOT NULL DEFAULT 0
        CHECK (creditos_acumulados >= 0),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.fidelidad_ajustes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL
        REFERENCES public.clientes(id) ON DELETE RESTRICT,
    creditos_anteriores BIGINT NOT NULL CHECK (creditos_anteriores >= 0),
    creditos_nuevos BIGINT NOT NULL CHECK (creditos_nuevos >= 0),
    completados_anteriores INTEGER NOT NULL CHECK (completados_anteriores >= 0),
    completados_nuevos INTEGER NOT NULL CHECK (completados_nuevos >= 0),
    motivo TEXT NOT NULL CHECK (BTRIM(motivo) <> ''),
    usuario_id UUID NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_fidelidad_ajustes_cliente_creado
    ON public.fidelidad_ajustes (cliente_id, creado_en DESC);

ALTER TABLE public.fidelidad_clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fidelidad_ajustes ENABLE ROW LEVEL SECURITY;

