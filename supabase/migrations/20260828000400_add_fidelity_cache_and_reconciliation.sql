ON public.fidelidad_clientes FOR UPDATE TO authenticated
USING ((SELECT petstore_private.es_admin_propietario()))
WITH CHECK ((SELECT petstore_private.es_admin_propietario()));

CREATE POLICY fidelidad_ajustes_select
ON public.fidelidad_ajustes FOR SELECT TO authenticated
USING ((SELECT petstore_private.es_admin_propietario()));

CREATE POLICY fidelidad_ajustes_insert
