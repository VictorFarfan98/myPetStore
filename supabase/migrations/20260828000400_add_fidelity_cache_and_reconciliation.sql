GRANT EXECUTE ON FUNCTION public.clientes_fidelidad_actualizar(BIGINT, INTEGER, TEXT) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.clientes_fidelidad_reconciliar() TO authenticated, service_role;
