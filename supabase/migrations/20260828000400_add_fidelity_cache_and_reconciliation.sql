WITH CHECK ((SELECT petstore_private.es_admin_propietario()));

GRANT SELECT, UPDATE ON TABLE public.fidelidad_clientes TO authenticated;
GRANT SELECT, INSERT ON TABLE public.fidelidad_ajustes TO authenticated;
GRANT ALL PRIVILEGES ON TABLE public.fidelidad_clientes, public.fidelidad_ajustes TO service_role;
GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.fidelidad_ajustes_id_seq TO authenticated, service_role;

CREATE TRIGGER trg_fidelidad_clientes_actualizado_en
BEFORE UPDATE ON public.fidelidad_clientes
FOR EACH ROW EXECUTE FUNCTION public.establecer_actualizado_en();

INSERT INTO public.fidelidad_clientes (cliente_id, creditos_acumulados)
SELECT c.id,
       COALESCE((
           SELECT COUNT(*)
           FROM public.registros_servicio rs
           INNER JOIN public.citas ci ON ci.id = rs.cita_id
           INNER JOIN public.mascotas m ON m.id = ci.mascota_id
           LEFT JOIN public.cupones cp ON cp.id = rs.cupon_id
           CROSS JOIN public.configuracion_sistema config
           WHERE m.cliente_id = c.id
             AND rs.estado = 'completado'
             AND rs.activo = TRUE
             AND rs.fin_real >= config.fidelidad_inicia_en
             AND (rs.cupon_id IS NULL OR cp.uso_unico = FALSE)
             AND config.id = 1
       ), 0)
FROM public.clientes c
ON CONFLICT (cliente_id) DO NOTHING;

CREATE OR REPLACE FUNCTION petstore_private.registro_servicio_cuenta_fidelidad(
    p_estado public.estado_registro_servicio,
    p_activo BOOLEAN,
    p_fin_real TIMESTAMPTZ,
    p_cupon_id UUID
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.configuracion_sistema config
        WHERE config.id = 1
          AND p_estado = 'completado'
          AND p_activo = TRUE
          AND p_fin_real >= config.fidelidad_inicia_en
          AND (
              p_cupon_id IS NULL
              OR NOT EXISTS (
                  SELECT 1
                  FROM public.cupones cp
                  WHERE cp.id = p_cupon_id
                    AND cp.uso_unico = TRUE
              )
          )
    );
$$;

CREATE OR REPLACE FUNCTION petstore_private.actualizar_fidelidad_desde_registro()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_cliente_id BIGINT;
    v_delta INTEGER := 0;
    v_anterior_cuenta BOOLEAN := FALSE;
    v_nueva_cuenta BOOLEAN;
BEGIN
    SELECT m.cliente_id
    INTO v_cliente_id
    FROM public.citas ci
    INNER JOIN public.mascotas m ON m.id = ci.mascota_id
    WHERE ci.id = NEW.cita_id;

    v_nueva_cuenta := petstore_private.registro_servicio_cuenta_fidelidad(
        NEW.estado, NEW.activo, NEW.fin_real, NEW.cupon_id
    );
    IF TG_OP = 'UPDATE' THEN
        v_anterior_cuenta := petstore_private.registro_servicio_cuenta_fidelidad(
            OLD.estado, OLD.activo, OLD.fin_real, OLD.cupon_id
        );
    END IF;

    IF v_nueva_cuenta AND NOT v_anterior_cuenta THEN
        v_delta := 1;
    ELSIF v_anterior_cuenta AND NOT v_nueva_cuenta THEN
        v_delta := -1;
    END IF;

    IF v_delta = 0 OR v_cliente_id IS NULL THEN
        RETURN NEW;
    END IF;

    PERFORM 1 FROM public.clientes WHERE id = v_cliente_id FOR UPDATE;

    IF v_delta > 0 THEN
        INSERT INTO public.fidelidad_clientes (cliente_id, creditos_acumulados)
        VALUES (v_cliente_id, 1)
        ON CONFLICT (cliente_id) DO UPDATE
        SET creditos_acumulados = public.fidelidad_clientes.creditos_acumulados + 1;
    ELSE
        UPDATE public.fidelidad_clientes
        SET creditos_acumulados = GREATEST(0, creditos_acumulados - 1)
        WHERE cliente_id = v_cliente_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_actualizar_fidelidad_desde_registro ON public.registros_servicio;
CREATE TRIGGER trg_actualizar_fidelidad_desde_registro
AFTER INSERT OR UPDATE OF estado, activo, fin_real, cupon_id ON public.registros_servicio
FOR EACH ROW EXECUTE FUNCTION petstore_private.actualizar_fidelidad_desde_registro();

CREATE OR REPLACE FUNCTION petstore_private.crear_fidelidad_cliente()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.fidelidad_clientes (cliente_id)
    VALUES (NEW.id)
    ON CONFLICT (cliente_id) DO NOTHING;
    RETURN NEW;
END;
$$;

